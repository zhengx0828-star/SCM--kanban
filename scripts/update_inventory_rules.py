def main() -> None:
    if not DB.exists():
        raise SystemExit(f"DB 不存在：{DB}")
    conn = sqlite3.connect(DB)
    try:
        for sort_order, title, content in RULES:
            row = conn.execute(
                "select id from rules where module=? and title=?", (MODULE, title)
            ).fetchone()
            if row:
                conn.execute(
                    "update rules set content=?, sort_order=?, updated_at=CURRENT_TIMESTAMP where id=?",
                    (content, sort_order, row[0]),
                )
                print(f"[update] {title}")
            else:
                conn.execute(
                    "insert into rules (module, title, content, sort_order) values (?,?,?,?)",
                    (MODULE, title, content, sort_order),
                )
                print(f"[insert] {title}")
        # 已废弃的旧条目（标题被新条目取代，直接删除）。
        # 注意：标题未变的条目只做 update，不要放进这里，否则会被删掉。
        for legacy in (
            "KPI 四卡口径（当前筛选视图内，按物料 PN 去重）",
            "日度推算、COV 与安全库存口径",
            "模块定位与数据来源（Excel 导入）",
            # 四卡改为 DOH 四档后，原「风险时间漏斗」标题不再成立（已改名为「下单时机分桶口径」）
            "风险时间漏斗（顶部四卡，按推算单元统计）",
            "预警状态与颜色（判定优先级从高到低，每格只落一种）",
            # 首次同步时误插入的重复条目（内容已并入第 3 条）
            "下单时机细条（原风险时间漏斗，已降级）",
        ):
            cur = conn.execute("delete from rules where module=? and title=?", (MODULE, legacy))
            if cur.rowcount:
                print(f"[remove] {legacy}")
        # 新标题与旧标题重名的情况：同 sort_order 去重，保留最新
        conn.execute(
            "delete from rules where module=? and id not in (select max(id) from rules where module=? group by sort_order)",
            (MODULE, MODULE),
        )
        conn.commit()
        print("\n当前库存管理规则：")
        for r in conn.execute(
            "select sort_order, title from rules where module=? order by sort_order", (MODULE,)
        ):
            print(f"  {r[0]}. {r[1]}")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
